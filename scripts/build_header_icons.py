#!/usr/bin/env python3
"""Regenerate the vendored header paths (requires fontTools, not used by builds).

Convert SVG arcs to cubic curves before PGF renders them. PGF can select the
wrong semicircle for a 180-degree arc, losing filled areas such as LinkedIn's
i dot and the location pin's hole. Keep upstream SVGs unchanged.
"""

from pathlib import Path
import xml.etree.ElementTree as ET

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.svgLib.path import parse_path


ROOT = Path(__file__).resolve().parents[1]
ICONS = {
    "Location": "location-dot",
    "Phone": "phone",
    "Email": "envelope",
    "GitHub": "github",
    "Medium": "medium",
    "LinkedIn": "linkedin-in",
    "ResearchGate": "researchgate",
}


def main() -> None:
    directory = ROOT / "assets" / "icons" / "fontawesome"
    lines = [
        "% Font Awesome Free 6.7.2 by Fonticons, Inc. — icons licensed CC BY 4.0.",
        "% Generated by scripts/build_header_icons.py from adjacent upstream SVGs.",
        "% SVG arcs are converted to cubic curves for reliable PGF rendering.",
        "% https://github.com/FortAwesome/Font-Awesome/tree/6.7.2/svgs",
        "% See LICENSE.txt and THIRD_PARTY_NOTICES.md for attribution.",
    ]
    for name, filename in ICONS.items():
        svg = ET.parse(directory / f"{filename}.svg").getroot()
        x, y, width, height = svg.attrib["viewBox"].split()
        if (x, y, height) != ("0", "0", "512"):
            raise ValueError(f"Unsupported viewBox for {filename}")
        pen = SVGPathPen(None, ntos=lambda value: f"{value:.6f}".rstrip("0").rstrip("."))
        for path in svg.findall("{http://www.w3.org/2000/svg}path"):
            parse_path(path.attrib["d"], pen)
        lines.append(
            rf"\newcommand{{\{name}Icon}}{{\HeaderIconShape{{{width}}}{{{pen.getCommands()}}}}}"
        )
    (directory / "paths.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
